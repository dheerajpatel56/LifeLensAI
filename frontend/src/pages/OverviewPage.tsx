import { FlaskConical, NotebookPen, Radar } from 'lucide-react'
import { Link } from 'react-router-dom'
import { api } from '../services/api'
import { useAsync } from '../hooks/useApi'
import { useDataset } from '../hooks/useDataset'
import { PageHeader } from '../components/layout/PageHeader'
import { Block, Grid, Readout } from '../components/layout/Workspace'
import {
  Button,
  Callout,
  ChartSkeleton,
  DataTable,
  EmptyState,
  ErrorState,
  Skeleton,
} from '../components/ui'
import { LinkButton } from '../components/ui/LinkButton'
import { InsightRow } from '../components/dashboard/InsightCard'
import {
  ClusterDistributionChart,
  RelationScatter,
  TrendLineChart,
} from '../components/charts'
import { formatDate, formatNumber } from '../utils/format'

export function OverviewPage() {
  const { dataset, filter, version, markStale } = useDataset()
  const source = dataset?.source

  const { data, error, loading, reload } = useAsync(
    () =>
      api.overview({
        source,
        start: filter.start ?? undefined,
        end: filter.end ?? undefined,
      }),
    [source, filter.start, filter.end, version],
  )

  const handleLoadDemo = async () => {
    await api.loadDemo(false)
    markStale()
    reload()
  }

  return (
    <div>
      <PageHeader
        title="Overview"
        meta={
          data
            ? `${data.filtered_count.toLocaleString()} of ${data.record_count.toLocaleString()} days${
                data.date_start ? ` · ${formatDate(data.date_start)} – ${formatDate(data.date_end)}` : ''
              }`
            : undefined
        }
        note="Every figure on this view is computed from the active dataset and the date window in the toolbar. Nothing here is cached or hardcoded; changing either re-runs the calculation on the server."
        actions={
          <>
            <LinkButton to="/check-in" icon={<NotebookPen className="size-3.5" />}>
              Add check-in
            </LinkButton>
            <LinkButton to="/patterns" variant="primary" icon={<Radar className="size-3.5" />}>
              Analyse
            </LinkButton>
          </>
        }
      />

      {error && <ErrorState message={error} onRetry={reload} />}

      {!error && (
        <div className="flex flex-col gap-6">
          {data?.is_synthetic && (
            <Callout tone="warning">
              Synthetic demo data — every value was generated by{' '}
              <code className="text-xs">scripts/generate_demo_dataset.py</code>. Patterns here are
              properties of the simulation.{' '}
              <Link to="/datasets" className="text-accent-ink underline">
                Switch to your own data
              </Link>
              .
            </Callout>
          )}

          {data && data.filtered_count === 0 ? (
            <EmptyState
              icon={<FlaskConical className="size-4" />}
              title={
                data.record_count === 0
                  ? 'This dataset is empty'
                  : 'No records inside the selected date range'
              }
              description={data.data_sufficiency.guidance}
              action={
                <div className="flex flex-wrap gap-1.5">
                  <Button variant="primary" onClick={() => void handleLoadDemo()}>
                    Load the demo dataset
                  </Button>
                  <LinkButton to="/check-in">Record today</LinkButton>
                </div>
              }
            />
          ) : (
            <>
              {/* Figure row: one rule, shared baseline, no tiles. */}
              {loading && !data ? (
                <div className="flex flex-wrap gap-x-10 gap-y-3 border-y border-line py-3">
                  {Array.from({ length: 5 }).map((_, index) => (
                    <div key={index} className="flex flex-col gap-1.5">
                      <Skeleton className="h-2.5 w-20" />
                      <Skeleton className="h-5 w-12" />
                    </div>
                  ))}
                </div>
              ) : (
                data && (
                  <div className="flex flex-wrap gap-x-10 gap-y-3 border-y border-line py-3">
                    {data.metrics.map((metric) => (
                      <Readout
                        key={metric.key}
                        label={metric.label}
                        value={
                          metric.value === null
                            ? '—'
                            : metric.unit === 'minutes'
                              ? Math.round(metric.value)
                              : metric.value.toFixed(1)
                        }
                        unit={metric.value === null ? undefined : metric.unit === '/10' ? '/10' : metric.unit}
                        sub={metric.value === null ? 'not recorded' : `n = ${metric.sample_size.toLocaleString()}`}
                        tone={metric.value === null ? 'muted' : 'default'}
                      />
                    ))}
                  </div>
                )
              )}

              {data && !data.data_sufficiency.sufficient && (
                <Callout tone="neutral">{data.data_sufficiency.guidance}</Callout>
              )}

              {/* Defined cells, not a stack of slabs. */}
              <Grid className="xl:grid-cols-3">
                <Block
                  label="Mood and productivity"
                  meta={
                    data
                      ? data.trend_granularity === 'daily'
                        ? 'daily'
                        : `${data.trend_granularity} means`
                      : undefined
                  }
                  span="xl:col-span-2"
                  note={
                    data && data.trend_granularity !== 'daily'
                      ? `Averaged per ${
                          data.trend_granularity === 'weekly' ? 'week' : 'month'
                        } because the selected range is long. Narrow the date window in the toolbar to resolve individual days.`
                      : 'One point per recorded day. Gaps are days with no record.'
                  }
                >
                  {loading && !data ? (
                    <ChartSkeleton height={260} />
                  ) : (
                    <TrendLineChart points={data?.trend ?? []} height={260} />
                  )}
                </Block>

                <Block
                  label="Routine groups"
                  meta={data ? `k = ${data.cluster_distribution.length}` : undefined}
                  note="K-Means over standardised lifestyle features. Labels are descriptive, derived from each group's own averages — not diagnoses."
                >
                  {loading && !data ? (
                    <ChartSkeleton height={260} />
                  ) : (
                    <ClusterDistributionChart items={data?.cluster_distribution ?? []} height={260} />
                  )}
                </Block>

                <Block
                  label="Sleep vs productivity"
                  meta={
                    data?.sleep_vs_productivity
                      ? `n = ${data.sleep_vs_productivity.sample_size.toLocaleString()}`
                      : undefined
                  }
                  note="A visible slope is an association in this dataset, not evidence that sleep caused the change."
                >
                  {loading && !data ? (
                    <ChartSkeleton height={220} />
                  ) : (
                    <RelationScatter series={data?.sleep_vs_productivity ?? null} height={220} />
                  )}
                </Block>

                <Block
                  label="Stress vs mood"
                  meta={
                    data?.mood_vs_stress
                      ? `n = ${data.mood_vs_stress.sample_size.toLocaleString()}`
                      : undefined
                  }
                  note="Both axes are self-reported on the same day, so they share whatever mood the day had."
                >
                  {loading && !data ? (
                    <ChartSkeleton height={220} />
                  ) : (
                    <RelationScatter
                      series={data?.mood_vs_stress ?? null}
                      color="var(--color-warning)"
                      height={220}
                    />
                  )}
                </Block>

                <Block
                  label="Recent"
                  meta={data ? `${data.recent_checkins.length} days` : undefined}
                >
                  {loading && !data ? (
                    <Skeleton className="h-52" />
                  ) : data && data.recent_checkins.length > 0 ? (
                    <DataTable minWidth="18rem">
                      <thead>
                        <tr className="border-b border-line bg-surface text-left">
                          <th scope="col" className="label px-2.5 py-1.5">Date</th>
                          <th scope="col" className="label px-2.5 py-1.5 text-right">Mood</th>
                          <th scope="col" className="label px-2.5 py-1.5 text-right">Prod.</th>
                          <th scope="col" className="label px-2.5 py-1.5 text-right">Sleep</th>
                        </tr>
                      </thead>
                      <tbody>
                        {data.recent_checkins.map((row) => (
                          <tr
                            key={row.date}
                            className="border-b border-line/70 transition-colors last:border-0 hover:bg-surface"
                          >
                            <td className="tnum px-2.5 py-1 text-body">{formatDate(row.date)}</td>
                            <td className="tnum px-2.5 py-1 text-right text-ink">
                              {formatNumber(row.mood_score, 0)}
                            </td>
                            <td className="tnum px-2.5 py-1 text-right text-ink">
                              {formatNumber(row.productivity_score, 0)}
                            </td>
                            <td className="tnum px-2.5 py-1 text-right text-body">
                              {formatNumber(row.sleep_hours)}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </DataTable>
                  ) : (
                    <EmptyState
                      title="No recent records"
                      description="Record a day to see it here."
                      action={<LinkButton to="/check-in">Record today</LinkButton>}
                    />
                  )}
                </Block>
              </Grid>

              <Block
                label="Notable patterns"
                meta={data ? `${data.top_patterns.length} findings` : undefined}
                actions={
                  <Link
                    to="/insights"
                    className="text-2xs text-accent-ink no-underline transition-colors hover:text-ink"
                  >
                    All insights →
                  </Link>
                }
              >
                {loading && !data ? (
                  <div className="flex flex-col gap-3">
                    {Array.from({ length: 3 }).map((_, index) => (
                      <Skeleton key={index} className="h-12" />
                    ))}
                  </div>
                ) : data && data.top_patterns.length > 0 ? (
                  <div>
                    {data.top_patterns.map((item) => (
                      <InsightRow key={item.id} item={item} />
                    ))}
                  </div>
                ) : (
                  <EmptyState
                    title="No pattern passed the evidence threshold"
                    description="Nothing in this range cleared the minimum sample size and strength needed to report."
                  />
                )}
              </Block>
            </>
          )}
        </div>
      )}
    </div>
  )
}
