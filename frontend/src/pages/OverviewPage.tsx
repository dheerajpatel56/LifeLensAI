import { Link } from 'react-router-dom'
import { FlaskConical, NotebookPen, Radar } from 'lucide-react'
import { api } from '../services/api'
import { useAsync } from '../hooks/useApi'
import { useDataset } from '../hooks/useDataset'
import { PageHeader } from '../components/layout/PageHeader'
import {
  Button,
  Callout,
  ChartSkeleton,
  EmptyState,
  ErrorState,
  Panel,
  SampleSize,
  Skeleton,
} from '../components/ui'
import { LinkButton } from '../components/ui/LinkButton'
import { MetricTile, MetricTileSkeleton } from '../components/dashboard/MetricTile'
import { InsightCard } from '../components/dashboard/InsightCard'
import {
  ChartFrame,
  ClusterDistributionChart,
  RelationScatter,
  TrendLineChart,
} from '../components/charts'
import { formatDate, formatNumber } from '../utils/format'

export function OverviewPage() {
  const { dataset, filter, version, markStale } = useDataset()
  const source = dataset?.source

  const { data, error, loading, reload } = useAsync(
    () =>
      api.overview({
        source,
        start: filter.start ?? undefined,
        end: filter.end ?? undefined,
      }),
    [source, filter.start, filter.end, version],
  )

  const handleLoadDemo = async () => {
    await api.loadDemo(false)
    markStale()
    reload()
  }

  return (
    <div>
      <PageHeader
        title="Overview"
        lede={
          data
            ? `${data.source_label} · ${data.filtered_count.toLocaleString()} day(s) in view${
                filter.start || filter.end
                  ? ` of ${data.record_count.toLocaleString()} recorded`
                  : ''
              }${
                data.date_start ? ` · ${formatDate(data.date_start)} – ${formatDate(data.date_end)}` : ''
              }`
            : 'Every figure below is computed from the active dataset and the selected date range.'
        }
        actions={
          <>
            <LinkButton to="/check-in" variant="secondary" icon={<NotebookPen className="size-4" />}>
              Add a check-in
            </LinkButton>
            <LinkButton to="/patterns" variant="primary" icon={<Radar className="size-4" />}>
              Analyse patterns
            </LinkButton>
          </>
        }
      />

      {error && <ErrorState message={error} onRetry={reload} />}

      {!error && (
        <div className="flex flex-col gap-5">
          {data?.is_synthetic && (
            <Callout tone="warning" title="You are looking at synthetic demo data">
              Every value in this dataset was generated by{' '}
              <code className="text-xs text-body">scripts/generate_demo_dataset.py</code>. The
              patterns below are properties of the simulation, not findings about real people.
              Switch to <Link to="/datasets" className="text-accent-ink underline">your own data</Link>{' '}
              to analyse real check-ins.
            </Callout>
          )}

          {data && data.filtered_count === 0 ? (
            <Panel title="Nothing recorded in this view">
              <EmptyState
                icon={<FlaskConical className="size-5" />}
                title={
                  data.record_count === 0
                    ? 'This dataset is empty'
                    : 'No records inside the selected date range'
                }
                description={data.data_sufficiency.guidance}
                action={
                  <div className="flex flex-wrap justify-center gap-2">
                    <Button variant="primary" onClick={() => void handleLoadDemo()}>
                      Load the demo dataset
                    </Button>
                    <LinkButton to="/check-in" variant="secondary">
                      Record today
                    </LinkButton>
                  </div>
                }
              />
            </Panel>
          ) : (
            <>
              {/* Metrics */}
              <div className="grid gap-3 [grid-template-columns:repeat(auto-fit,minmax(10.5rem,1fr))]">
                {loading && !data
                  ? Array.from({ length: 5 }).map((_, index) => <MetricTileSkeleton key={index} />)
                  : data?.metrics.map((metric) => <MetricTile key={metric.key} metric={metric} />)}
              </div>

              {data && !data.data_sufficiency.sufficient && (
                <Callout tone="neutral" title="Limited data in this view">
                  {data.data_sufficiency.guidance}
                </Callout>
              )}

              {/* Trends */}
              <Panel
                title="Mood and productivity over time"
                description={
                  data
                    ? data.trend_granularity === 'daily'
                      ? 'Self-reported scores, one point per recorded day. Gaps are days with no record.'
                      : `Self-reported scores, averaged per ${
                          data.trend_granularity === 'weekly' ? 'week' : 'month'
                        } because the selected range is long. Narrow the date range to see individual days.`
                    : 'Self-reported scores over time.'
                }
              >
                {loading && !data ? (
                  <ChartSkeleton />
                ) : (
                  <TrendLineChart points={data?.trend ?? []} />
                )}
              </Panel>

              {/* Relationships */}
              <div className="grid gap-5 lg:grid-cols-2">
                <Panel title="Sleep against productivity">
                  {loading && !data ? (
                    <ChartSkeleton height={240} />
                  ) : (
                    <ChartFrame
                      title="One point per recorded day"
                      sampleSize={data?.sleep_vs_productivity?.sample_size ?? 0}
                      caption="A visible slope is an association in this dataset, not evidence that sleep caused the change."
                    >
                      <RelationScatter series={data?.sleep_vs_productivity ?? null} />
                    </ChartFrame>
                  )}
                </Panel>

                <Panel title="Stress against mood">
                  {loading && !data ? (
                    <ChartSkeleton height={240} />
                  ) : (
                    <ChartFrame
                      title="One point per recorded day"
                      sampleSize={data?.mood_vs_stress?.sample_size ?? 0}
                      caption="Both axes are self-reported on the same day, so they share whatever mood the day had."
                    >
                      <RelationScatter
                        series={data?.mood_vs_stress ?? null}
                        color="var(--color-cyan)"
                      />
                    </ChartFrame>
                  )}
                </Panel>
              </div>

              {/* Patterns + clusters */}
              <div className="grid gap-5 xl:grid-cols-[1.4fr_1fr]">
                <Panel
                  title="Most notable patterns"
                  description="Pulled from the same correlation and rule mining the Pattern Explorer runs."
                  actions={
                    <Link
                      to="/insights"
                      className="text-xs font-medium text-accent-ink transition-colors hover:text-ink"
                    >
                      All insights
                    </Link>
                  }
                >
                  {loading && !data ? (
                    <div className="grid gap-3 sm:grid-cols-2">
                      {Array.from({ length: 4 }).map((_, index) => (
                        <Skeleton key={index} className="h-32" />
                      ))}
                    </div>
                  ) : data && data.top_patterns.length > 0 ? (
                    <div className="grid gap-3 sm:grid-cols-2">
                      {data.top_patterns.map((item) => (
                        <InsightCard key={item.id} item={item} />
                      ))}
                    </div>
                  ) : (
                    <EmptyState
                      title="No pattern passed the evidence threshold"
                      description="Nothing in this range cleared the minimum sample size and strength needed to report. More days of data will change that."
                    />
                  )}
                </Panel>

                <Panel
                  title="Routine groups"
                  description="K-Means over standardised lifestyle features."
                  footer={
                    data && data.cluster_distribution.length > 0
                      ? 'Labels are descriptive, derived from each group’s own averages — not diagnoses.'
                      : undefined
                  }
                >
                  {loading && !data ? (
                    <ChartSkeleton height={200} />
                  ) : (
                    <ClusterDistributionChart items={data?.cluster_distribution ?? []} />
                  )}
                </Panel>
              </div>

              {/* Recent */}
              <Panel
                title="Recent check-ins"
                description="The latest days inside the selected range."
              >
                {loading && !data ? (
                  <Skeleton className="h-40" />
                ) : data && data.recent_checkins.length > 0 ? (
                  <div className="-mx-4 overflow-x-auto sm:-mx-5">
                    <table className="w-full min-w-[34rem] text-sm">
                      <thead>
                        <tr className="border-b border-line text-left text-2xs uppercase tracking-wide text-faint">
                          <th scope="col" className="px-4 py-2 font-medium sm:px-5">Date</th>
                          <th scope="col" className="px-3 py-2 text-right font-medium">Mood</th>
                          <th scope="col" className="px-3 py-2 text-right font-medium">Productivity</th>
                          <th scope="col" className="px-3 py-2 text-right font-medium">Sleep</th>
                          <th scope="col" className="px-3 py-2 text-right font-medium">Stress</th>
                          <th scope="col" className="px-4 py-2 font-medium sm:px-5">Notes</th>
                        </tr>
                      </thead>
                      <tbody>
                        {data.recent_checkins.map((row) => (
                          <tr
                            key={row.date}
                            className="border-b border-line/60 transition-colors last:border-0 hover:bg-raised"
                          >
                            <td className="px-4 py-2 text-body sm:px-5">{formatDate(row.date)}</td>
                            <td className="tnum px-3 py-2 text-right text-ink">
                              {formatNumber(row.mood_score, 0)}
                            </td>
                            <td className="tnum px-3 py-2 text-right text-ink">
                              {formatNumber(row.productivity_score, 0)}
                            </td>
                            <td className="tnum px-3 py-2 text-right text-body">
                              {formatNumber(row.sleep_hours)} h
                            </td>
                            <td className="tnum px-3 py-2 text-right text-body">
                              {formatNumber(row.stress_score, 0)}
                            </td>
                            <td className="max-w-[18rem] truncate px-4 py-2 text-muted sm:px-5">
                              {row.notes ?? '—'}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                ) : (
                  <EmptyState
                    title="No recent records"
                    description="Record a day to see it appear here."
                    action={
                      <LinkButton to="/check-in" variant="primary">
                        Record today
                      </LinkButton>
                    }
                  />
                )}
              </Panel>

              {data && (
                <p className="flex items-center gap-2 text-2xs text-faint">
                  Figures computed from {data.filtered_count.toLocaleString()} record(s).
                  <SampleSize n={data.filtered_count} />
                </p>
              )}
            </>
          )}
        </div>
      )}
    </div>
  )
}
